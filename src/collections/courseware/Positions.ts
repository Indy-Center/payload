/**
 * The short name a stored position is shown and found by, or null: its `shortName` field, which
 * holds the served value (vNAS's, else the override, else the generated one: `servedShortName` in
 * `src/positions/short-name.ts`, applied by `setServed`). The title and the scenario pickers read
 * it here.
 */
export const shownShortName = (position: Pick<Position, 'shortName'>): string | null =>
  position.shortName || null

/** "FLM 83 · Falmouth 83", or "ZID_TMU · ZID TMU" where there is no short name. */
export const positionTitle = (position: Pick<Position, 'shortName' | 'callsign' | 'name'>) =>
  `${shownShortName(position) ?? position.callsign} · ${position.name}`

/** The short name served and the title follow every save: a sync, or an override changed. */
const setServed: CollectionBeforeChangeHook<Position> = ({ data, originalDoc }) => {
  const merged = {
    ...originalDoc,
    ...data,
    indyShortName: { ...originalDoc?.indyShortName, ...data.indyShortName },
  } as Position
  const shortName = servedShortName(merged)
  return { ...data, shortName, title: positionTitle({ ...merged, shortName }) }
}

