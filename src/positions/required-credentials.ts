import type { FilterOptions, FilterOptionsProps, Where } from 'payload'
import { idOf } from '@/courseware/ids'
import { rowLabelComponent } from '@/courseware/row-label-component'
import type { Position } from '@/payload-types'
import { indyFact, servedFact } from './indy-facts'
import { positionType, type PositionType } from './position-type'

/**
 * The credentials a controller must hold to work a position (decision 0060), shaped like a
 * course's prerequisites: rows, each met by holding any one of its credentials, every row needing
 * to be met. Nothing acts on them yet; apps read them from the catalogue.
 */

/**
 * The generated rule, by position type and credential code: each inner list is one row. Kept in
 * code, so a change is a deploy and the next sync. Guard, TMU and any other type require none.
 */
export const DEFAULT_REQUIRED_CODES: Partial<Record<PositionType, string[][]>> = {
  RMP: [['S-GC']],
  DEL: [['S-GC']],
  GND: [['A-GC']],
  TWR: [['A-LC']],
  APP: [['T-RC']],
  DEP: [['T-RC']],
  CTR: [['E-RC'], ['T2-CTR']],
}

/** Every credential code the rule names. */
export const DEFAULT_CODES = [...new Set(Object.values(DEFAULT_REQUIRED_CODES).flat(2))]

/** Credential ids by code. */
export type CredentialIds = ReadonlyMap<string, string>

/** The codes the rule names that Credentials lacks. */
export const missingCodes = (idByCode: CredentialIds) =>
  DEFAULT_CODES.filter((code) => !idByCode.has(code))

/**
 * The rows generated for a position of this callsign, as credential ids. A code Credentials lacks
 * leaves out its place: a row left with no credential is dropped, so the rest still stand.
 */
export function generatedRequiredCredentials(
  callsign: string,
  idByCode: CredentialIds,
): { anyOf: string[] }[] {
  return (DEFAULT_REQUIRED_CODES[positionType(callsign)] ?? [])
    .map((codes) => ({ anyOf: codes.flatMap((code) => idByCode.get(code) ?? []) }))
    .filter((row) => row.anyOf.length > 0)
}

type Rows = { anyOf?: (string | { id: string })[] | null }[] | null | undefined

/** The rows as plain lists of credential ids, whether stored, populated or generated. */
export const rowsOf = (rows: Rows): string[][] =>
  (rows ?? []).map((row) => (row.anyOf ?? []).flatMap((credential) => idOf(credential) ?? []))

/** Whether two lists of rows name the same credentials in the same places. */
export const sameRows = (a: Rows, b: Rows): boolean =>
  JSON.stringify(rowsOf(a)) === JSON.stringify(rowsOf(b))

/** What the field's description and the catalogue's type both say, since apps apply it. */
export const HOW_TO_READ =
  'Every row must be met; a row is met by holding any one of its credentials. A certification is also met by any certification ranked higher (an A-LC holder meets S-GC and A-GC), but an endorsement counts only when named. No rating is stored.'

/** The position's required credentials: generated by type, overridable by a CMS admin. */
export const indyRequiredCredentialsField = indyFact({
  name: 'indyRequiredCredentials',
  label: 'Required credentials',
  description: `What a controller must hold to work this position. ${HOW_TO_READ} An override replaces the whole list.`,
  value: rowsField(),
  overrideValue: rowsField(pickableCredential),
})

/**
 * The override offers and accepts credentials as a course's prerequisites do: retired ones are left
 * out, other than those the position's stored override already names, so it still saves.
 */
async function pickableCredential({ id, req }: FilterOptionsProps): Promise<Where> {
  const live: Where = { retired: { not_equals: true } }
  if (!id) return live
  const stored = await req.payload.findByID({
    collection: 'positions',
    id,
    depth: 0,
    disableErrors: true,
    req,
  })
  const named = (stored?.indyRequiredCredentials?.override ?? [])
    .flatMap((row) => row.anyOf ?? [])
    .map((credential) => idOf(credential))
    .filter((credential): credential is string => credential !== null)
  return named.length === 0 ? live : { or: [live, { id: { in: named } }] }
}

function rowsField(filterOptions?: FilterOptions) {
  return {
    type: 'array' as const,
    labels: { singular: 'Requirement', plural: 'Requirements' },
    admin: { components: { RowLabel: rowLabelComponent('prerequisite') } },
    fields: [
      {
        name: 'anyOf',
        label: 'Holds one of these',
        type: 'relationship' as const,
        relationTo: 'credentials' as const,
        hasMany: true as const,
        required: true,
        ...(filterOptions ? { filterOptions } : {}),
      },
    ],
  }
}

/** The required credentials served as credential ids: the override if set, else the generated. */
export const servedRequiredCredentials = (
  position: Pick<Position, 'indyRequiredCredentials'>,
): string[][] => rowsOf(servedFact(position.indyRequiredCredentials))
